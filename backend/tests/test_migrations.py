import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Engine, inspect

from tests.conftest import alembic_config

pytestmark = pytest.mark.db


def test_migrations_create_the_expected_tables(engine: Engine) -> None:
    tables = set(inspect(engine).get_table_names())

    assert {
        "static_version",
        "route",
        "stop",
        "trip",
        "service_calendar",
        "service_calendar_date",
    } <= tables


def test_models_and_migrations_agree(engine: Engine, database_url: str) -> None:
    """Fails when a model changes without a matching migration."""
    try:
        command.check(alembic_config(database_url))
    except AutogenerateDiffsDetected as exc:
        pytest.fail(f"models differ from migrations: {exc}")
